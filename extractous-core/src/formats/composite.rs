//! What Tika's composite parser reads, in extractous's configuration of it
//! (`TikaNativeMain.createParser`): the types it has a parser for, where
//! [`super::parser_for`], walking a document's types as `CompositeParser.getParser` does, stops
//! for a type no native parser reads.

mod parsers;

use crate::mime::MediaType;
use parsers::TIKA_PARSERS;

/// Whether Tika's composite parser has a parser of its own for `kind`, rather than the one of a
/// type `kind` specializes.
pub(super) fn tika_reads(kind: &MediaType) -> bool {
    TIKA_PARSERS
        .binary_search_by(|(listed, _)| (*listed).cmp(kind.as_str()))
        .is_ok()
}

#[cfg(test)]
mod tests {
    #[cfg(feature = "tika")]
    use std::collections::HashMap;
    #[cfg(feature = "tika")]
    use std::fmt::Write as _;

    use super::*;
    #[cfg(feature = "tika")]
    use crate::config::{ParserConfigs, TesseractOcrConfig};
    use crate::formats::{self, PARSERS};
    #[cfg(feature = "tika")]
    use crate::formats::{parity, PARSER_OVERRIDE};
    #[cfg(feature = "tika")]
    use crate::isolate::isolate;
    #[cfg(feature = "tika")]
    use crate::mime;
    #[cfg(feature = "tika")]
    use crate::tika::{self, EmbeddedOutcome};

    /// The parsers Tika's path records before the one its composite parser picks.
    #[cfg(feature = "tika")]
    const COMPOSITES: [&str; 2] = [
        "org.apache.tika.parser.DefaultParser",
        "org.apache.tika.parser.AutoDetectParser",
    ];
    const EMPTY_PARSER: &str = "org.apache.tika.parser.EmptyParser";

    /// The class of the parser Tika's composite parser picks for a document of `kind`, as the
    /// document's `tk:parsed-by` records it: Tika's path parses a byte with `kind` as the type
    /// that overrides the detected one, OCR skipped.
    #[cfg(feature = "tika")]
    fn tika_class(kind: &str) -> String {
        let configs = ParserConfigs {
            ocr: TesseractOcrConfig::new().set_skip_ocr(true),
            ..Default::default()
        };
        let parsed = tika::parse_embedded(
            isolate().unwrap(),
            b"x",
            &[(PARSER_OVERRIDE, kind)],
            &configs,
        )
        .unwrap_or_else(|e| panic!("Tika's path does not parse a byte of {kind}: {e}"));
        let EmbeddedOutcome::Parsed { metadata, .. } = parsed.outcome else {
            panic!("Tika's path fails a byte of {kind}");
        };
        metadata
            .get("tk:parsed-by")
            .into_iter()
            .flatten()
            .find(|parser| !COMPOSITES.contains(&parser.as_str()))
            .unwrap_or_else(|| panic!("Tika's path records no parser for {kind}"))
            .clone()
    }

    /// Each type Tika's default types declare whose parser is not the one of its supertype,
    /// with the class of that parser, in the order of the types' names.
    #[cfg(feature = "tika")]
    fn tika_parsers() -> Vec<(String, String)> {
        let mut classes: HashMap<String, String> = HashMap::new();
        let mut class_of = |kind: &str| {
            classes
                .entry(kind.to_owned())
                .or_insert_with(|| tika_class(kind))
                .clone()
        };
        let mut table = Vec::new();
        for declared in mime::declared_types() {
            let kind = MediaType::named(declared);
            let class = class_of(kind.as_str());
            let inherited = match mime::lineage(&kind).nth(1) {
                Some(supertype) => class_of(supertype.as_str()),
                None => EMPTY_PARSER.to_owned(),
            };
            if class != inherited {
                table.push((kind.as_str().to_owned(), class));
            }
        }
        table.sort();
        table
    }

    #[cfg(feature = "tika")]
    fn source(table: &[(String, String)]) -> String {
        let mut source = String::from(
            "//! Generated by `just composite-reference` from Tika's path: each type Tika's default \
             types\n//! declare whose parser in Tika's composite parser is not the one of its \
             supertype, with\n//! the class of that parser, in the order of the types' \
             names.\n\npub(super) const TIKA_PARSERS: &[(&str, &str)] = &[\n",
        );
        for (kind, class) in table {
            writeln!(source, "    ({kind:?}, {class:?}),").unwrap();
        }
        source.push_str("];\n");
        source
    }

    /// The table is what Tika's path picks, in order; unless `COMPOSITE_REFERENCE` names the
    /// file to write it to instead, as the source of [`TIKA_PARSERS`].
    #[cfg(feature = "tika")]
    #[test]
    fn lists_the_types_tikas_composite_parser_reads() {
        let table = tika_parsers();
        if let Some(path) = std::env::var_os("COMPOSITE_REFERENCE") {
            std::fs::write(path, source(&table)).unwrap();
            return;
        }
        let listed: Vec<(String, String)> = TIKA_PARSERS
            .iter()
            .map(|(kind, class)| ((*kind).to_owned(), (*class).to_owned()))
            .collect();
        assert_eq!(listed, table);
    }

    /// The types routed to a native parser other than the one replacing Tika's, and why.
    #[cfg(feature = "tika")]
    const EXCEPTIONS: [(&str, &str); 1] = [("application/zstd", parity::ZSTD_WITHOUT_ZSTD_JNI)];

    /// Every type routed to a native parser is one Tika's composite parser reads with the
    /// parser the native one replaces, but for the [`EXCEPTIONS`].
    #[cfg(feature = "tika")]
    #[test]
    fn routes_each_type_to_the_parser_tika_picks() {
        let mut differences = Vec::new();
        for declared in mime::declared_types() {
            let kind = MediaType::named(declared);
            if EXCEPTIONS
                .iter()
                .any(|(exception, _)| *exception == kind.as_str())
            {
                continue;
            }
            let Ok(native) = formats::parser_for(kind.as_str()) else {
                continue;
            };
            let tika = tika_class(kind.as_str());
            if native.tika_name() != tika {
                differences.push(format!("{kind}: {} where Tika picks {tika}", native.name()));
            }
        }
        assert!(differences.is_empty(), "{}", differences.join("\n"));
    }

    #[test]
    fn falls_back_to_the_empty_parser_for_a_type_tika_has_no_parser_for() {
        let parser = formats::parser_for("application/x-berkeley-db").unwrap();
        assert_eq!(parser.tika_name(), EMPTY_PARSER);
        let parser = formats::parser_for("not a media type").unwrap();
        assert_eq!(parser.tika_name(), EMPTY_PARSER);
        assert!(PARSERS
            .iter()
            .any(|parser| parser.tika_name() == EMPTY_PARSER));
    }

    #[test]
    fn walks_to_the_supertype_tika_reads_a_type_as() {
        assert_eq!(
            formats::parser_for("text/x-matlab").unwrap().name(),
            formats::parser_for("text/plain").unwrap().name()
        );
        assert!(formats::parser_for("application/x-matlab-data").is_err());
        assert!(formats::parser_for("image/x-portable-pixmap").is_err());
        assert!(TIKA_PARSERS.is_sorted());
    }
}
