static BY_NAME: LazyLock<FastMap<&'static [u8], Op>> =
    LazyLock::new(|| OPERATORS.iter().copied().collect());

impl Op {
    /// The operator `systemdict` defines under `name`.
    pub(super) fn named(name: &[u8]) -> Option<Op> {
        BY_NAME.get(name).copied()
    }

    /// The name of the operator, as `cvs` writes it.
    pub(super) fn name(self) -> &'static [u8] {
        OPERATORS
            .iter()
            .find(|(_, op)| *op == self)
            .map_or(b"--nostringval--", |(name, _)| name)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_each_operator_once() {
        let mut names: Vec<&[u8]> = OPERATORS.iter().map(|(name, _)| *name).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), OPERATORS.len());
        assert_eq!(Op::named(b"show"), Some(Op::Show));
        assert_eq!(Op::Show.name(), b"show");
        assert_eq!(Op::named(b"nosuchoperator"), None);
    }
}
